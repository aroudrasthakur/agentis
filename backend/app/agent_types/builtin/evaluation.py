"""Evaluation Agent: assesses outputs, trajectories, tool calls, and workflows."""

from __future__ import annotations

from app.agent_types.builtin._helpers import (
    COST,
    CURRENCY,
    DATA,
    DATA_SOURCE_SELECTOR,
    EVALUATION,
    HIGHER_IS_BETTER,
    JSON,
    LOWER_IS_BETTER,
    MILLISECONDS,
    MODEL_SELECTOR,
    MULTI_SELECT,
    NUMBER,
    PERCENTAGE,
    PERFORMANCE,
    QUALITY,
    RELIABILITY,
    SCORE,
    SELECT,
    WORKFLOW,
    metric,
    param,
    when,
)
from app.agent_types.schemas import AgentTypeDefinition

PARAMETERS = [
    param(
        "evaluation_target",
        "Evaluation target",
        SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("final_output", "Final output"),
            ("trajectory", "Trajectory"),
            ("tool_calls", "Tool calls"),
            ("retrieval_results", "Retrieval results"),
            ("full_workflow", "Full workflow"),
        ],
        default="final_output",
    ),
    param(
        "evaluation_dimensions",
        "Evaluation dimensions",
        MULTI_SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("accuracy", "Accuracy"),
            ("groundedness", "Groundedness"),
            ("relevance", "Relevance"),
            ("completeness", "Completeness"),
            ("coherence", "Coherence"),
            ("safety", "Safety"),
            ("format_compliance", "Format compliance"),
            ("efficiency", "Efficiency"),
        ],
        default=["accuracy", "groundedness"],
    ),
    param(
        "scoring_method",
        "Scoring method",
        SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("llm_judge", "LLM judge"),
            ("rubric", "Rubric"),
            ("heuristic", "Heuristic"),
            ("exact_match", "Exact match"),
            ("pairwise_comparison", "Pairwise comparison"),
        ],
        default="llm_judge",
    ),
    param(
        "scoring_scale",
        "Scoring scale",
        SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("binary", "Binary"),
            ("likert_5", "Likert 1-5"),
            ("percentage", "Percentage"),
            ("continuous_0_1", "Continuous 0-1"),
        ],
        default="continuous_0_1",
    ),
    param("pass_threshold", "Pass threshold", NUMBER, EVALUATION, required=True, min=0, max=1, default=0.7),
    param(
        "evaluation_frequency",
        "Evaluation frequency",
        SELECT,
        WORKFLOW,
        required=True,
        choices=[
            ("every_run", "Every run"),
            ("sampled", "Sampled"),
            ("scheduled", "Scheduled"),
            ("on_demand", "On demand"),
        ],
        default="sampled",
    ),
    param(
        "sampling_rate",
        "Sampling rate",
        NUMBER,
        WORKFLOW,
        required=True,
        min=0,
        max=1,
        default=0.1,
        visible_when=when("evaluation_frequency", "equals", "sampled"),
    ),
    param(
        "reference_answer_required",
        "Reference-answer requirement",
        SELECT,
        DATA,
        required=True,
        choices=[
            ("not_required", "Not required"),
            ("optional", "Optional"),
            ("required", "Required"),
        ],
        default="optional",
    ),
    param(
        "ground_truth_source",
        "Ground-truth source",
        DATA_SOURCE_SELECTOR,
        DATA,
        required=True,
        visible_when=when("reference_answer_required", "not_equals", "not_required"),
    ),
    param("judge_model", "Judge model", MODEL_SELECTOR, EVALUATION, required=True, visible_when=when("scoring_method", "equals", "llm_judge")),
    param(
        "disagreement_handling",
        "Disagreement handling",
        SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("lowest_score", "Take lowest score"),
            ("average", "Average scores"),
            ("majority_vote", "Majority vote"),
            ("rerun_evaluation", "Re-run evaluation"),
            ("return_control_to_runtime", "Return control to runtime"),
        ],
        default="average",
    ),
    param(
        "evaluation_output_schema",
        "Evaluation output schema",
        JSON,
        DATA,
        required=True,
        description="Shape of the score record this agent emits.",
    ),
    param(
        "severity_classifications",
        "Severity classifications",
        MULTI_SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("info", "Info"),
            ("minor", "Minor"),
            ("major", "Major"),
            ("critical", "Critical"),
        ],
        default=["minor", "major", "critical"],
    ),
    param(
        "evaluation_failure_behavior",
        "Evaluation failure behavior",
        SELECT,
        WORKFLOW,
        required=True,
        choices=[
            ("skip", "Skip evaluation"),
            ("retry", "Retry"),
            ("mark_unscored", "Mark unscored"),
            ("return_control_to_runtime", "Return control to runtime"),
        ],
        default="mark_unscored",
    ),
    param(
        "comparison_baseline",
        "Comparison baseline",
        SELECT,
        EVALUATION,
        required=True,
        choices=[
            ("none", "None"),
            ("previous_version", "Previous version"),
            ("golden_dataset", "Golden dataset"),
            ("production_average", "Production average"),
        ],
        default="previous_version",
    ),
    param(
        "regression_thresholds",
        "Regression thresholds",
        JSON,
        EVALUATION,
        required=True,
        description="Per-dimension score drops that count as a regression.",
    ),
]

METRICS = [
    metric("reference_agreement", "Agreement with reference labels", QUALITY, PERCENTAGE, HIGHER_IS_BETTER, required=True),
    metric("false_positive_rate", "False-positive rate", QUALITY, PERCENTAGE, LOWER_IS_BETTER, required=True),
    metric("false_negative_rate", "False-negative rate", QUALITY, PERCENTAGE, LOWER_IS_BETTER, required=True),
    metric("evaluation_consistency", "Evaluation consistency", RELIABILITY, SCORE, HIGHER_IS_BETTER),
    metric("calibration", "Calibration", QUALITY, SCORE, HIGHER_IS_BETTER),
    metric("inter_rater_agreement", "Inter-rater agreement", QUALITY, SCORE, HIGHER_IS_BETTER),
    metric("evaluation_latency", "Evaluation latency", PERFORMANCE, MILLISECONDS, LOWER_IS_BETTER),
    metric("cost_per_evaluation", "Cost per evaluation", COST, CURRENCY, LOWER_IS_BETTER),
    metric("regression_detection_rate", "Regression detection rate", QUALITY, PERCENTAGE, HIGHER_IS_BETTER),
    metric("score_stability", "Score stability", RELIABILITY, SCORE, HIGHER_IS_BETTER),
]

TYPE = AgentTypeDefinition(
    id="evaluation",
    name="Evaluation Agent",
    slug="evaluation",
    description=(
        "Assesses outputs, trajectories, tool calls, retrieval results, or complete workflows."
    ),
    use_cases=[
        "Scoring agent answers against a rubric",
        "Detecting quality regressions between versions",
        "Sampling production traffic for offline review",
    ],
    capabilities=[
        "Scoring and grading",
        "Baseline comparison",
        "Regression detection",
    ],
    default_autonomy_level=2,
    default_risk_level="low",
    parameter_definitions=PARAMETERS,
    metric_definitions=METRICS,
)
