    metric("task_accuracy", "Task accuracy", QUALITY, PERCENTAGE, HIGHER_IS_BETTER, required=True),
    metric("domain_correctness", "Domain correctness", QUALITY, PERCENTAGE, HIGHER_IS_BETTER, required=True),
    metric("schema_validity", "Schema validity", RELIABILITY, PERCENTAGE, HIGHER_IS_BETTER),
    metric("citation_coverage", "Citation coverage", QUALITY, PERCENTAGE, HIGHER_IS_BETTER),
    metric("groundedness", "Groundedness", QUALITY, SCORE, HIGHER_IS_BETTER, required=True),
