"""Task / Domain Agent: specialized work inside a task category or business domain."""

from __future__ import annotations

from app.agent_types.builtin._helpers import (
    BOOLEAN,
    CAPABILITIES,
    DATA,
    DATA_SOURCE_SELECTOR,
    EVALUATION,
    HIGHER_IS_BETTER,
    IDENTITY,
    JSON,
    LOWER_IS_BETTER,
    MILLISECONDS,
    MULTI_SELECT,
    NUMBER,
    PERCENTAGE,
    PERFORMANCE,
    QUALITY,
    RELIABILITY,
    SAFETY,
    SCORE,
    SELECT,
    TASK_SUCCESS,
    TEXT,
    TEXTAREA,
    TOOLS,
    WORKFLOW,
    metric,
    param,
    when,
)
from app.agent_types.schemas import AgentTypeDefinition

